export function fmt(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, key) => (key in vars ? String(vars[key]) : m));
}

// Spielzeit in Sekunden, genau wie der Kern sie in lib.get.info schreibt (library/describe.py,
// human_time): „12 Std. 30 Min.“, „35 Min.“, „weniger als eine Minute“. So sagen Unterzeile, Marke
// und Karte im Hub dasselbe.
export function playtimeText(seconds) {
  const s = Math.floor(Number(seconds) || 0);
  if (s <= 0) return "";
  if (s < 60) return S.lessThanMinute;
  const minutesAll = Math.floor(s / 60);
  const hours = Math.floor(minutesAll / 60);
  const minutes = minutesAll % 60;
  if (!hours) return fmt(S.minutes, { n: minutes });
  return minutes ? fmt(S.hours, { n: hours }) + " " + fmt(S.minutes, { n: minutes }) : fmt(S.hours, { n: hours });
}

// Zeitpunkt (Unix-Sekunden) als "heute", "gestern", "vor 3 Tagen", danach kurzes Datum ("24. Sept. 2026")
export function whenText(timestamp, now = Date.now() / 1000) {
  if (!timestamp) return "";
  const day = (t) => { const d = new Date(t * 1000); d.setHours(0, 0, 0, 0); return d.getTime(); };
  const days = Math.round((day(now) - day(timestamp)) / 86400000);
  if (days <= 0) return S.today;
  if (days === 1) return S.yesterday;
  if (days < 7) return fmt(S.daysAgo, { n: days });
  return new Date(timestamp * 1000).toLocaleDateString(S.locale, { day: "numeric", month: "short", year: "numeric" });
}
